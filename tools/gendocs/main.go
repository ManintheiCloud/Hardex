// Command gendocs regenerates docs/rules.md from rule metadata, so the rule
// reference can never drift from the code. Run: go run ./tools/gendocs
package main

import (
	"bytes"
	"fmt"
	"os"
	"strings"

	"github.com/ManintheiCloud/Hardex/baselines"
	"github.com/ManintheiCloud/Hardex/kubernetes"
)

func main() {
	out := "docs/rules.md"
	if len(os.Args) > 1 {
		out = os.Args[1]
	}
	doc, err := Generate()
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	if err := os.WriteFile(out, doc, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

// Generate renders the rule reference.
func Generate() ([]byte, error) {
	reg, err := kubernetes.Registry()
	if err != nil {
		return nil, err
	}
	inProfile := map[string][]string{}
	for _, name := range baselines.ProfileNames() {
		p, err := baselines.Profile(name)
		if err != nil {
			return nil, err
		}
		for _, id := range p.Rules {
			inProfile[id] = append(inProfile[id], name)
		}
	}
	var b bytes.Buffer
	b.WriteString("# Rule reference\n\n<!-- Generated by `go run ./tools/gendocs`. Do not edit by hand. -->\n\n")
	b.WriteString("Severity is the default; individual findings may be raised or lowered where the rule says so, and operators can override it in configuration.\n\n")
	b.WriteString("| ID | Severity | Category | Title | Profiles |\n|---|---|---|---|---|\n")
	for _, r := range reg.All() {
		m := r.Metadata()
		fmt.Fprintf(&b, "| [%s](#%s) | %s | %s | %s | %s |\n", m.ID, strings.ToLower(m.ID), m.Severity, m.Category, m.Title, strings.Join(inProfile[m.ID], ", "))
	}
	for _, r := range reg.All() {
		m := r.Metadata()
		fmt.Fprintf(&b, "\n## %s\n\n**%s** — %s, %s\n\n", m.ID, m.Title, m.Severity, m.Category)
		fmt.Fprintf(&b, "**Checks:** %s\n\n**Why it matters:** %s\n\n**Remediation:** %s\n", m.Description, m.Rationale, m.Remediation)
		if m.Limitations != "" {
			fmt.Fprintf(&b, "\n**Known limitations:** %s\n", m.Limitations)
		}
		if len(m.References) > 0 {
			b.WriteString("\n**References:**\n\n")
			for _, ref := range m.References {
				if ref.URL != "" {
					fmt.Fprintf(&b, "- %s: [%s](%s)\n", ref.Framework, ref.Control, ref.URL)
				} else {
					fmt.Fprintf(&b, "- %s: %s\n", ref.Framework, ref.Control)
				}
			}
		}
	}
	return b.Bytes(), nil
}
